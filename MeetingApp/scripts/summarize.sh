#!/bin/bash
# Шаг 2: транскрипт -> саммари в файл summary.md рядом с транскриптом.
# Использование: ./summarize.sh "/путь/к/transcript.txt" "Название встречи" ["словарь терминов"]
#
# Саммари никуда не выгружается: куда его отправить (Notion, Заметки, файл),
# человек решает сам кнопкой в истории — см. export_summary.sh.
set -e

TRANSCRIPT="$1"
NAME="$2"
GLOSSARY="$3"

if [ -z "$TRANSCRIPT" ] || [ ! -s "$TRANSCRIPT" ]; then
  echo "Не найден или пуст файл транскрипта: $TRANSCRIPT"
  exit 1
fi

# Свои копии компонентов лежат в <папка данных>/bin — папку находим по месту
# самого скрипта, поэтому тестовая и рабочая сборки берут каждая своё. Дальше
# идут системные пути: если у человека уже стоят ffmpeg или whisper, сгодятся
# и они. $HOME/.local/bin — туда ставит себя Claude Code.
BIN_DIR="$(cd "$(dirname "$0")/.." && pwd)/bin"
export PATH="$BIN_DIR:$HOME/.local/bin:/opt/homebrew/bin:/usr/local/bin:$HOME/.npm-global/bin:/usr/bin:/bin:$PATH"

if ! command -v claude &> /dev/null; then
  echo "Claude Code не найден. Установка: npm install -g @anthropic-ai/claude-code"
  exit 1
fi

OUT_DIR=$(dirname "$TRANSCRIPT")
SUMMARY_FILE="$OUT_DIR/summary.md"
rm -f "$SUMMARY_FILE"

GLOSSARY_INSTRUCTION=""
if [ -n "$GLOSSARY" ]; then
  GLOSSARY_INSTRUCTION="
Справочник терминов и имён, которые встречаются в этих разговорах: $GLOSSARY
Если в транскрипте явно искажённое написание термина или имени из справочника,
используй правильное написание из справочника."
fi

echo "Делаю саммари…"

claude -p "Прочитай файл транскрипта встречи: $TRANSCRIPT (название встречи: \"$NAME\").
Транскрипт получен автоматическим распознаванием речи. Если в строках есть подписи
«Я» и «Собеседники» — это разметка по дорожкам: «Я» говорит владелец компьютера.
Если подписей нет, разметки по говорящим нет вовсе. В нём бывают ошибки распознавания, особенно в аббревиатурах, фамилиях и
названиях систем, а также повторы — ориентируйся на смысл, а не на дословность.
$GLOSSARY_INSTRUCTION

Точность важнее гладкости. Строгие правила:
- Аббревиатуры, названия систем и имена, которых нет в справочнике и которые распознались
  неуверенно, НЕ расшифровывай и не «исправляй» наугад — оставь как услышано и пометь [?].
- Не приписывай людям роли, должности и связи, которые прямо не прозвучали. Не объединяй
  разных людей или организации в одно, если это не сказано явно.
- Цифры, суммы, даты и сроки — только те, что прозвучали; не округляй и не додумывай.
- В договорённостях указывай ответственного и срок, только если они прямо названы;
  иначе пиши «ответственный не назван» / «срок не назван».
- Если чего-то в разговоре не было — раздел пропусти, не выдумывай.
- Не пиши вступлений о качестве записи, разметке по говорящим и ошибках
  распознавания: это и так известно, а читателю нужна суть разговора.
- Не упоминай здоровье, лечение, самочувствие, семейные и прочие личные
  обстоятельства участников, даже если они прозвучали в разговоре: саммари
  читают коллеги, а к рабочей повестке это отношения не имеет. Если человек
  о чём-то договорился или что-то поручил, пиши только саму договорённость,
  без объяснения личных причин.

Сделай структурированное саммари на русском языке со следующими разделами:
контекст и проблема; принятые решения; договорённости и следующие шаги; открытые вопросы.
Раздел о сомнительных местах распознавания не нужен — неуверенные слова просто
помечай [?] прямо в тексте.

Придумай встрече короткое название по сути разговора: 3-6 слов, без даты и
без слова «встреча». Если разговор был об одной теме — назови её; если тем
несколько — перечисли главные через запятую. Поставь это название заголовком
первой строки саммари.

Запиши получившееся саммари целиком (в формате markdown, без лишних комментариев от себя)
в файл $SUMMARY_FILE с помощью инструмента Write.

В самой последней строке ответа выведи это же название в виде
TITLE: <название> — приложение подставит его в список встреч.

Ничего не уточняй и не спрашивай — выполни все шаги самостоятельно." \
  --allowedTools "Read" "Write" \
  --max-turns 20

if [ ! -s "$SUMMARY_FILE" ]; then
  echo "Саммари не было сохранено в файл — что-то пошло не так на стороне Claude Code."
  exit 1
fi

echo "Саммари готово: $SUMMARY_FILE"
