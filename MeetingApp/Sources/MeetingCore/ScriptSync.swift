import Foundation

// Скрипты внутри приложения.
//
// Раньше скрипты раскладывала сборка — прямо в папку данных на этой машине.
// Из-за этого приложение нельзя было просто отдать другому человеку: .app
// запускался, но работать ему было нечем. По той же причине скрипты и
// приложение разъезжались после обновления: бинарник новый, скрипты старые.
// Теперь скрипты лежат внутри бандла, а приложение раскладывает их само.
public enum ScriptSync {
    // Какие скрипты надо записать: те, которых на диске нет, и те, что
    // отличаются от вложенных в приложение. Остальное не трогаем — в папке
    // могут лежать и чужие файлы, стирать их приложение не вправе.
    public static func outdatedNames(bundled: [String: String], installed: [String: String]) -> [String] {
        return bundled
            .filter { name, content in installed[name] != content }
            .map { $0.key }
            .sorted()
    }
}
